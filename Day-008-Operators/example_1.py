# Day 008 · Operators — Arithmetic and assignment
# Run: python example_1.py

a, b = 17, 5
print("a + b  =", a + b)
print("a - b  =", a - b)
print("a * b  =", a * b)
print("a / b  =", a / b)
print("a // b =", a // b)
print("a % b  =", a % b)
print("a ** 2 =", a ** 2)

count = 10
count += 5
count *= 2
print("count =", count)
